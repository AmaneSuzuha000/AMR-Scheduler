def __getattr__(name: str) -> object:
    """Lazily load PyTorch agent symbols so CPU rollout workers skip CUDA DLL commit."""
    if name in ("DuelingQNetwork", "RLCVCRAgent", "ReplayBuffer"):
        from amr_sched.rl import agent as _agent

        return getattr(_agent, name)
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
