"""加急任务动态重调度。

动态重调度要求
--------------
「考虑**加急任务插入**情况下的**动态重调度**方法」

问题定义
--------
静态分配只在任务下达时做一次决策。加急任务到达时，若所有 AGV 都已
被普通任务占用，加急任务只能排队——这与"加急"的语义直接矛盾。

三种对照策略
------------
1. **仅队列优先**（``NONE``）：加急任务在分配时排到队首，但不打断任何在执行任务。
   实现简单，代价是加急任务仍可能等很久。
2. **抢占未取货任务**（``PREEMPT_UNPICKED``）：允许加急任务"抢走"一台
   **正在空驶去取货、尚未装货**的 AGV。被抢的任务退回待分配队列。
3. **允许载货返程**（``PREEMPT_ANY``，仅离散仿真对照）：允许载货车在节点
   改走回程，但在回到原取货点并完成模拟卸货前，任务与货物仍由原车持有。

为什么只抢"未取货"的
--------------------
抢占已装货的 AGV 要把物料送回原处或就地卸下，产生真实的搬运浪费。
空驶阶段被抢占**没有任何物料损失**，只是多跑了一段空路。
因此 ``PREEMPT_UNPICKED`` 是**零物料代价**的抢占，工程上可接受；
载货对照记录实际走过的载货去程和返程时间；卸货耗时影响完成与响应时间。
"""

from __future__ import annotations

from enum import Enum


class ReschedulePolicy(str, Enum):
    """加急任务到达时的重调度策略。"""

    NONE = "none"
    """不重调度：加急只在分配排序上占优。"""

    PREEMPT_UNPICKED = "preempt_unpicked"
    """允许抢占"未取货"的普通任务。"""

    PREEMPT_ANY = "preempt_any"
    """允许抢占"未取货"**或**"已装货"的普通任务。

    为什么要有这一档
    ----------------
    它不是为了更好，而是为了**量化代价**。前面说"抢已装货车会产生
    真实搬运浪费"，但从来没人量过浪费多大。这一档把上限打开，
    其实际返程耗时、任务响应与交付差异可与 PREEMPT_UNPICKED 比较。

    被抢的已装货车**载货驶回原取货点**，按模拟处理时间卸货后再接加急任务。
    返程计入实际里程，物料浪费指标只计已实际走完的载货移动时间。"""
